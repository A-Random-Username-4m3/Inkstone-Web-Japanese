#!/usr/bin/env python3
"""Build Inkstone Japanese built-in vocabulary lists.

Uses the sharded ``data/jmdict/`` runtime dictionary generated by
``tools/build_japanese_dictionary.py`` and Jonathan Waller's community JLPT
vocabulary lists as redistributed by stephenmk/yomitan-jlpt-vocab.

The script uses only Python's standard library. JLPT CSVs may either be supplied
locally with ``--jlpt-dir`` or downloaded automatically from GitHub.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
import sys
import urllib.request

try:
    from .data_revision import bump_data_revision
except ImportError:  # direct script execution / importlib fixture loading
    tools_dir = str(Path(__file__).resolve().parent)
    if tools_dir not in sys.path:
        sys.path.insert(0, tools_dir)
    from data_revision import bump_data_revision


JLPT_LEVELS = ("n5", "n4", "n3", "n2", "n1")
JLPT_PROJECT_URL = "https://github.com/stephenmk/yomitan-jlpt-vocab"
JLPT_RAW_BASE = (
    "https://raw.githubusercontent.com/stephenmk/"
    "yomitan-jlpt-vocab/main/original_data"
)
WALLER_ATTRIBUTION = "Jonathan Waller JLPT Resources"
COMMON_DEFAULT_LIMIT = 10000


def load_json(path: Path):
    with path.open("r", encoding="utf-8") as stream:
        return json.load(stream)


def validate_jmdict(dataset: dict) -> None:
    if not isinstance(dataset, dict) or dataset.get("schemaVersion") not in {1, 2}:
        raise ValueError("Unsupported or invalid legacy JMdict dataset")
    if not isinstance(dataset.get("entries"), dict):
        raise ValueError("JMdict dataset has no entries object")


def load_jmdict_entries(path: Path) -> dict[str, dict]:
    """Load entries from the sharded runtime dictionary or legacy monolith."""
    if path.is_file():
        dataset = load_json(path)
        validate_jmdict(dataset)
        return dataset["entries"]

    manifest_path = path / "manifest.json"
    if not manifest_path.exists():
        raise ValueError(f"JMdict manifest not found: {manifest_path}")
    manifest = load_json(manifest_path)
    if not isinstance(manifest, dict) or manifest.get("schemaVersion") != 3:
        raise ValueError("Unsupported or invalid sharded JMdict manifest")
    shard_names = manifest.get("entryShards")
    shard_count = manifest.get("shardCount")
    if not isinstance(shard_count, int) or shard_count <= 0:
        raise ValueError("JMdict manifest has an invalid shardCount")
    if not isinstance(shard_names, list) or len(shard_names) != shard_count:
        raise ValueError("JMdict manifest entryShards do not match shardCount")

    entries: dict[str, dict] = {}
    for index, filename in enumerate(shard_names):
        shard = load_json(path / filename)
        if (
            not isinstance(shard, dict)
            or shard.get("schemaVersion") != 3
            or shard.get("kind") != "entries"
            or shard.get("shard") != index
            or not isinstance(shard.get("entries"), dict)
        ):
            raise ValueError(f"Invalid JMdict entry shard: {filename}")
        entries.update(shard["entries"])
    return entries


def read_csv_rows(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        expected = {"jmdict_seq", "kana", "kanji", "waller_definition"}
        if not reader.fieldnames or not expected.issubset(reader.fieldnames):
            raise ValueError(
                f"{path} does not look like a Waller/yomitan-jlpt-vocab CSV"
            )
        return [
            {key: (value or "").strip() for key, value in row.items()}
            for row in reader
        ]


def download_csv(level: str, target: Path) -> Path:
    target.parent.mkdir(parents=True, exist_ok=True)
    url = f"{JLPT_RAW_BASE}/{level}.csv"
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "Inkstone-Japanese-list-builder/1"},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        target.write_bytes(response.read())
    return target


def priority_score(record: dict) -> tuple:
    tags = record.get("priority") or []
    nf_values = []
    for tag in tags:
        if isinstance(tag, str) and tag.startswith("nf"):
            try:
                nf_values.append(int(tag[2:]))
            except ValueError:
                pass
    nf_rank = min(nf_values) if nf_values else 99
    tier = 0 if any(tag in {"news1", "ichi1", "spec1", "gai1"} for tag in tags) else 1
    if "spec2" in tags:
        tier = min(tier, 1)
    return (
        tier,
        nf_rank,
        len(str(record.get("written") or "")),
        int(record.get("sequence") or 0),
        str(record.get("reading") or ""),
        str(record.get("written") or ""),
    )


def build_sequence_index(entries: dict[str, dict]) -> dict[int, list[dict]]:
    by_sequence: dict[int, list[dict]] = {}
    for record in entries.values():
        try:
            sequence = int(record.get("sequence"))
        except (TypeError, ValueError):
            continue
        by_sequence.setdefault(sequence, []).append(record)
    for records in by_sequence.values():
        records.sort(key=priority_score)
    return by_sequence


def build_pair_index(entries: dict[str, dict]) -> dict[tuple[str, str], list[dict]]:
    by_pair: dict[tuple[str, str], list[dict]] = {}
    for record in entries.values():
        written = str(record.get("written") or "")
        reading = str(record.get("reading") or "")
        if not written or not reading:
            continue
        by_pair.setdefault((written, reading), []).append(record)
    for records in by_pair.values():
        records.sort(key=priority_score)
    return by_pair


def _source_sequence(source_row: dict[str, str]) -> int | None:
    try:
        return int(source_row.get("jmdict_seq", ""))
    except (TypeError, ValueError):
        return None


def resolve_jlpt_record(
    source_row: dict[str, str],
    by_sequence: dict[int, list[dict]],
    by_pair: dict[tuple[str, str], list[dict]],
) -> tuple[dict | None, str]:
    sequence = _source_sequence(source_row)
    reading = source_row.get("kana", "")
    written = source_row.get("kanji", "") or reading
    exact_pair = by_pair.get((written, reading), [])

    # The Waller-derived CSV carries JMdict sequence IDs, but JMdict is a live
    # dictionary: readings are occasionally split into new entries. Prefer the
    # current exact spelling+reading pair, using the source sequence only to
    # disambiguate when the same pair exists in more than one entry.
    if sequence is not None:
        for record in exact_pair:
            if int(record.get("sequence") or 0) == sequence:
                return record, "exact"
    if len(exact_pair) == 1:
        return exact_pair[0], "current-pair-remap"
    if len(exact_pair) > 1:
        common_exact = [record for record in exact_pair if record.get("common") is True]
        if len(common_exact) == 1:
            # Older JLPT/EDICT-derived rows can collapse homographs that JMdict
            # now keeps as separate entries.  When only one exact pair is
            # marked common, prefer that entry; otherwise stay conservative.
            return common_exact[0], "current-pair-common-remap"
        return None, "ambiguous-current-pair"

    # If the exact spelling has genuinely changed but the old sequence still
    # exists, retain the previous conservative same-reading spelling fallback.
    if sequence is not None:
        candidates = by_sequence.get(sequence, [])
        same_reading = [record for record in candidates if record.get("reading") == reading]
        if same_reading:
            return same_reading[0], "spelling-fallback"
    return None, "unresolved"


def unresolved_reason(
    source_row: dict[str, str],
    by_sequence: dict[int, list[dict]],
    by_pair: dict[tuple[str, str], list[dict]],
) -> str:
    reading = source_row.get("kana", "")
    written = source_row.get("kanji", "") or reading
    exact_pair = by_pair.get((written, reading), [])
    if len(exact_pair) > 1:
        return "ambiguous exact spelling/reading in current JMdict"

    sequence = _source_sequence(source_row)
    if sequence is None:
        return "no exact current JMdict pair and invalid source sequence"
    candidates = by_sequence.get(sequence, [])
    if not candidates:
        return "no exact current JMdict pair and source sequence not found"
    if reading and not any(record.get("reading") == reading for record in candidates):
        return "no exact current JMdict pair; reading not found for source sequence"
    return "spelling/reading pair not resolved"


def record_to_tsv(record: dict) -> str:
    definitions = [
        str(value).replace("\t", " ").replace("\r", " ").replace("\n", " ").strip()
        for value in record.get("definitions") or []
        if str(value).strip()
    ]
    definition = "; ".join(dict.fromkeys(definitions))
    values = [
        f"jmdict:{record['id']}",
        str(record["written"]),
        str(record["reading"]),
        definition,
    ]
    return "\t".join(value.replace("\t", " ").replace("\r", " ").replace("\n", " ") for value in values)


def build_jlpt_list(
    source_rows: list[dict[str, str]],
    by_sequence: dict[int, list[dict]],
    by_pair: dict[tuple[str, str], list[dict]],
) -> tuple[list[dict], int, int, list[dict[str, str]]]:
    resolved = []
    substitutions = 0
    remapped = 0
    missing = []
    seen = set()
    for source_row in source_rows:
        record, resolution = resolve_jlpt_record(source_row, by_sequence, by_pair)
        if not record:
            missing.append({
                **source_row,
                "_reason": unresolved_reason(source_row, by_sequence, by_pair),
            })
            continue
        study_id = f"jmdict:{record['id']}"
        if study_id in seen:
            continue
        seen.add(study_id)
        if resolution == "spelling-fallback":
            substitutions += 1
        elif resolution in {"current-pair-remap", "current-pair-common-remap"}:
            remapped += 1
        resolved.append(record)

    # Waller's source files are primarily kana-sorted. Inkstone uses list order
    # for sequential new cards, so prefer stronger JMdict commonness evidence
    # while preserving source order as the stable tie breaker.
    source_position = {f"jmdict:{record['id']}": i for i, record in enumerate(resolved)}
    resolved.sort(
        key=lambda record: (
            priority_score(record),
            source_position[f"jmdict:{record['id']}"],
        )
    )
    return resolved, substitutions, remapped, missing


def build_common_list(entries: dict[str, dict], limit: int) -> list[dict]:
    # Avoid flooding the list with alternate spelling/reading pairs from the
    # same JMdict entry. Keep the strongest representative pair per sequence.
    best_by_sequence: dict[int, dict] = {}
    for record in entries.values():
        if not record.get("common"):
            continue
        sequence = int(record.get("sequence") or 0)
        existing = best_by_sequence.get(sequence)
        if existing is None or priority_score(record) < priority_score(existing):
            best_by_sequence[sequence] = record
    records = sorted(best_by_sequence.values(), key=priority_score)
    return records[: max(0, limit)]


def write_tsv(path: Path, records: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        for record in records:
            stream.write(record_to_tsv(record))
            stream.write("\n")



def write_unresolved_report(
    path: Path,
    unresolved_by_level: dict[str, list[dict[str, str]]],
) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "level",
        "reason",
        "jmdict_seq",
        "written",
        "reading",
        "source_definition",
    ]
    count = 0
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fieldnames, dialect="excel-tab")
        writer.writeheader()
        for level in JLPT_LEVELS:
            for row in unresolved_by_level.get(level, []):
                writer.writerow({
                    "level": level.upper(),
                    "reason": row.get("_reason", "unresolved"),
                    "jmdict_seq": row.get("jmdict_seq", ""),
                    "written": row.get("kanji", "") or row.get("kana", ""),
                    "reading": row.get("kana", ""),
                    "source_definition": row.get("waller_definition", ""),
                })
                count += 1
    return count

def write_manifest(path: Path, common_count: int) -> None:
    manifest = {}
    for level in JLPT_LEVELS:
        upper = level.upper()
        manifest[f"jlpt-{level}"] = {
            "category": "JLPT",
            "name": f"JLPT {upper}",
            "path": f"data/lists/jlpt-{level}.tsv",
        }
    manifest["common-japanese"] = {
        "category": "General",
        "name": f"JMdict Common Japanese ({common_count:,})",
        "path": "data/lists/common-japanese.tsv",
    }
    with path.open("w", encoding="utf-8") as stream:
        json.dump(manifest, stream, ensure_ascii=False, indent=2)
        stream.write("\n")


def write_sources(
    path: Path,
    level_counts: dict[str, int],
    common_count: int,
    unresolved_count: int,
    unresolved_report: Path,
) -> None:
    payload = {
        "jlpt": {
            "project": "stephenmk/yomitan-jlpt-vocab",
            "projectUrl": JLPT_PROJECT_URL,
            "underlyingSource": WALLER_ATTRIBUTION,
            "official": False,
            "counts": {level.upper(): level_counts[level] for level in JLPT_LEVELS},
            "unresolvedCount": unresolved_count,
            "unresolvedReport": str(unresolved_report).replace("\\", "/"),
        },
        "commonJapanese": {
            "source": "JMdict priority/common markers",
            "count": common_count,
            "note": "A convenience subset, not an official frequency ranking.",
        },
    }
    with path.open("w", encoding="utf-8") as stream:
        json.dump(payload, stream, ensure_ascii=False, indent=2)
        stream.write("\n")


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--jmdict", type=Path, default=Path("data/jmdict"))
    parser.add_argument("--output-dir", type=Path, default=Path("data/lists"))
    parser.add_argument(
        "--jlpt-dir",
        type=Path,
        help="Directory containing n5.csv ... n1.csv. If omitted, download them.",
    )
    parser.add_argument(
        "--download-dir",
        type=Path,
        default=Path(".cache/jlpt-vocab"),
        help="Where automatically downloaded JLPT CSVs are cached.",
    )
    parser.add_argument(
        "--unresolved-report",
        type=Path,
        default=Path("data/lists/jlpt-unresolved.tsv"),
        help="TSV report containing JLPT rows that could not be mapped to JMdict.",
    )
    parser.add_argument(
        "--common-limit",
        type=int,
        default=COMMON_DEFAULT_LIMIT,
        help=f"Maximum Common Japanese entries (default: {COMMON_DEFAULT_LIMIT}).",
    )
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    jmdict_path = args.jmdict
    if (
        jmdict_path == Path("data/jmdict")
        and not jmdict_path.exists()
        and Path("data/jmdict.json").exists()
    ):
        # Transitional compatibility for projects that have not rebuilt JMdict
        # since the sharded runtime format was introduced.
        jmdict_path = Path("data/jmdict.json")
    entries = load_jmdict_entries(jmdict_path)
    by_sequence = build_sequence_index(entries)
    by_pair = build_pair_index(entries)

    level_counts = {}
    total_missing = 0
    total_substitutions = 0
    total_remapped = 0
    unresolved_by_level: dict[str, list[dict[str, str]]] = {}
    for level in JLPT_LEVELS:
        if args.jlpt_dir:
            csv_path = args.jlpt_dir / f"{level}.csv"
        else:
            csv_path = args.download_dir / f"{level}.csv"
            if not csv_path.exists():
                print(f"Downloading {level.upper()} JLPT source data...", file=sys.stderr)
                download_csv(level, csv_path)
        rows = read_csv_rows(csv_path)
        records, substitutions, remapped, missing = build_jlpt_list(
            rows, by_sequence, by_pair
        )
        write_tsv(args.output_dir / f"jlpt-{level}.tsv", records)
        level_counts[level] = len(records)
        total_missing += len(missing)
        total_substitutions += substitutions
        total_remapped += remapped
        unresolved_by_level[level] = missing
        print(
            f"Wrote {len(records)} {level.upper()} record(s) "
            f"({substitutions} spelling fallback(s), {remapped} current-JMdict remap(s), "
            f"{len(missing)} unresolved)."
        )
        if missing:
            preview = ", ".join(
                f"{row.get('kanji') or row.get('kana')}【{row.get('kana')}】"
                for row in missing[:5]
            )
            print(f"  Unresolved examples: {preview}", file=sys.stderr)

    common_records = build_common_list(entries, args.common_limit)
    write_tsv(args.output_dir / "common-japanese.tsv", common_records)
    print(f"Wrote {len(common_records)} Common Japanese record(s).")

    unresolved_count = write_unresolved_report(
        args.unresolved_report,
        unresolved_by_level,
    )
    write_manifest(Path("data/lists.json"), len(common_records))
    write_sources(
        args.output_dir / "SOURCES.json",
        level_counts,
        len(common_records),
        unresolved_count,
        args.unresolved_report,
    )
    print(
        "Updated data/lists.json and data/lists/SOURCES.json; "
        f"wrote {unresolved_count} unresolved row(s) to {args.unresolved_report}."
    )
    if total_missing:
        print(
            f"Warning: {total_missing} JLPT row(s) could not be matched to this JMdict build.",
            file=sys.stderr,
        )
    if total_remapped:
        print(
            f"Note: {total_remapped} JLPT row(s) were remapped by exact spelling/reading "
            "because the source JMdict sequence is stale or missing.",
            file=sys.stderr,
        )
    if total_substitutions:
        print(
            f"Note: {total_substitutions} JLPT row(s) used a same-reading JMdict spelling fallback.",
            file=sys.stderr,
        )
    revision = bump_data_revision()
    print(f"Updated offline data cache revision to {revision}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
